        "\n",
        "    agents = load_agents()\n",
        "\n",
        "    aliases = {\n",
        "\n",
        "        \"news\":\n",
        "            \"daily_news\",\n",
        "\n",
        "        \"tip\":\n",
        "            \"stem_tip\",\n",
        "\n",
        "        \"project\":\n",
