        "# =========================================================\n",
        "# DATE FILTER\n",
        "# =========================================================\n",
        "\n",
        "def filter_recent(\n",
        "    articles: list[dict[str, Any]],\n",
        "    hours: int = 48,\n",
        ") -> list[dict[str, Any]]:\n",
        "    \"\"\"\n",
        "    Keep articles published within the last N hours.\n",
        "\n",
        "    Articles without a readable publication date\n",
        "    are retained.\n",
        "    \"\"\"\n",
        "\n",
        "    cutoff = (\n",
        "        datetime.now(\n",
        "            timezone.utc\n",
        "        )\n",
        "        - timedelta(\n",
        "            hours=hours\n",
        "        )\n",
        "    )\n",
        "\n",
        "    results = []\n",
        "\n",
        "    for article in articles:\n",
        "\n",
        "        published = article.get(\n",
        "            \"published\"\n",
        "        )\n",
        "\n",
        "        if not published:\n",
        "\n",
        "            results.append(\n",
        "                article\n",
        "            )\n",
        "\n",
        "            continue\n",
        "\n",
        "        try:\n",
        "\n",
        "            article_time = (\n",
        "                datetime.fromisoformat(\n",
        "                    published\n",
        "                )\n",
        "            )\n",
        "\n",
        "            if (\n",
        "                article_time\n",
        "                >= cutoff\n",
        "            ):\n",
        "\n",
        "                results.append(\n",
        "                    article\n",
        "                )\n",
        "\n",
        "        except ValueError:\n",
        "\n",
        "            results.append(\n",
        "                article\n",
        "            )\n",
        "\n",
        "    return results\n",
        "\n",
