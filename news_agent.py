        "# =========================================================\n",
        "# GEMINI\n",
        "# =========================================================\n",
        "\n",
        "def summarize_with_gemini(\n",
        "    articles: list[NewsArticle],\n",
        ") -> list[NewsArticle]:\n",
        "    \"\"\"\n",
        "    Ask the shared Gemini service to summarize the articles.\n",
        "\n",
        "    Expected services/gemini.py interface:\n",
        "\n",
        "        summarize_news(articles)\n",
        "\n",
        "    The function should return a list of dictionaries.\n",
        "    \"\"\"\n",
        "\n",
        "    if not articles:\n",
        "        return []\n",
        "\n",
        "    try:\n",
        "\n",
        "        from services.gemini import summarize_news\n",
        "\n",
        "    except ImportError as exc:\n",
        "\n",
        "        logger.error(\n",
        "            \"Gemini service is not available.\"\n",
        "        )\n",
        "\n",
        "        raise ImportError(\n",
        "            \"Create services/gemini.py before running \"\n",
        "            \"the news agent.\"\n",
        "        ) from exc\n",
        "\n",
        "    payload = []\n",
        "\n",
        "    for index, article in enumerate(articles):\n",
        "\n",
        "        payload.append(\n",
        "            {\n",
        "                \"id\": index,\n",
        "                \"title\": article.title,\n",
        "                \"source\": article.source,\n",
        "                \"category\": article.category,\n",
        "                \"description\": article.description,\n",
        "                \"url\": article.url,\n",
        "            }\n",
        "        )\n",
        "\n",
        "    logger.info(\n",
        "        \"Sending %d articles to Gemini...\",\n",
        "        len(payload),\n",
        "    )\n",
        "\n",
        "    try:\n",
        "\n",
        "        results = summarize_news(payload)\n",
        "\n",
        "    except Exception as exc:\n",
        "\n",
        "        logger.exception(\n",
        "            \"Gemini summarization failed: %s\",\n",
        "            exc,\n",
        "        )\n",
        "\n",
        "        return articles\n",
        "\n",
        "    if not isinstance(results, list):\n",
        "        logger.warning(\n",
        "            \"Gemini returned unexpected result.\"\n",
        "        )\n",
        "        return articles\n",
        "\n",
        "    for index, result in enumerate(results):\n",
        "\n",
        "        if index >= len(articles):\n",
        "            break\n",
        "\n",
        "        if not isinstance(result, dict):\n",
        "            continue\n",
        "\n",
        "        articles[index].summary = clean_text(\n",
        "            result.get(\"summary\", \"\")\n",
        "        )\n",
        "\n",
        "        articles[index].importance = clean_text(\n",
        "            result.get(\"importance\", \"Medium\")\n",
        "        )\n",
        "\n",
        "    return articles\n",
        "\n",
        "\n",
        "# =========================================================\n",
        "# RANK NEWS\n",
        "# =========================================================\n",
        "\n",
        "def rank_articles(\n",
        "    articles: list[NewsArticle],\n",
        ") -> list[NewsArticle]:\n",
        "    \"\"\"\n",
        "    Rank articles by AI-assigned importance.\n",
        "\n",
        "    High > Medium > Low\n",
        "    \"\"\"\n",
        "\n",
        "    priority = {\n",
        "        \"high\": 3,\n",
        "        \"medium\": 2,\n",
        "        \"low\": 1,\n",
        "    }\n",
        "\n",
        "    articles.sort(\n",
        "        key=lambda article: priority.get(\n",
        "            article.importance.lower(),\n",
        "            2,\n",
        "        ),\n",
        "        reverse=True,\n",
        "    )\n",
        "\n",
        "    return articles\n",
