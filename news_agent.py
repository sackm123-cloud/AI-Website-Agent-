        "# =========================================================\n",
        "# HELPERS\n",
        "# =========================================================\n",
        "\n",
        "def clean_text(value: Any) -> str:\n",
        "    \"\"\"Convert HTML/text input into clean text.\"\"\"\n",
        "\n",
        "    if value is None:\n",
        "        return \"\"\n",
        "\n",
        "    text = str(value)\n",
        "\n",
        "    # Basic HTML cleanup\n",
        "    text = text.replace(\"<p>\", \" \")\n",
        "    text = text.replace(\"</p>\", \" \")\n",
        "    text = text.replace(\"<br>\", \" \")\n",
        "    text = text.replace(\"<br/>\", \" \")\n",
        "    text = text.replace(\"<br />\", \" \")\n",
        "\n",
        "    return \" \".join(text.split())\n",
        "\n",
        "\n",
        "def get_source_from_url(url: str) -> str:\n",
        "    \"\"\"Extract a readable source name from a URL.\"\"\"\n",
        "\n",
        "    try:\n",
        "        hostname = urlparse(url).netloc.lower()\n",
        "\n",
        "        if hostname.startswith(\"www.\"):\n",
        "            hostname = hostname[4:]\n",
        "\n",
        "        return hostname\n",
        "\n",
        "    except Exception:\n",
        "        return \"\"\n",
        "\n",
        "\n",
        "def normalize_url(url: str) -> str:\n",
        "    \"\"\"Normalize article URL for duplicate detection.\"\"\"\n",
        "\n",
        "    if not url:\n",
        "        return \"\"\n",
        "\n",
        "    return url.strip().rstrip(\"/\")\n",
        "\n",
        "\n",
        "def is_valid_article(title: str, url: str) -> bool:\n",
        "    \"\"\"Basic article validation.\"\"\"\n",
        "\n",
        "    if not title:\n",
        "        return False\n",
        "\n",
        "    if len(title.strip()) < 10:\n",
        "        return False\n",
        "\n",
        "    if not url.startswith((\"http://\", \"https://\")):\n",
        "        return False\n",
        "\n",
        "    return True\n",
        "\n",
        "\n",
        "# =========================================================\n",
        "# RSS COLLECTION\n",
        "# =========================================================\n",
        "\n",
        "def collect_from_feed(\n",
        "    feed_url: str,\n",
        "    category: str,\n",
        "    limit: int = 10,\n",
        ") -> list[NewsArticle]:\n",
        "    \"\"\"Collect articles from one RSS feed.\"\"\"\n",
        "\n",
        "    feedparser = load_rss_library()\n",
        "\n",
        "    logger.info(\n",
        "        \"Reading RSS feed: %s\",\n",
        "        feed_url,\n",
        "    )\n",
        "\n",
        "    try:\n",
        "        feed = feedparser.parse(feed_url)\n",
        "\n",
        "    except Exception as exc:\n",
        "        logger.error(\n",
        "            \"Failed to read feed %s: %s\",\n",
        "            feed_url,\n",
        "            exc,\n",
        "        )\n",
        "        return []\n",
        "\n",
        "    articles: list[NewsArticle] = []\n",
        "\n",
        "    entries = getattr(feed, \"entries\", [])\n",
        "\n",
        "    for entry in entries[:limit]:\n",
        "\n",
        "        title = clean_text(\n",
        "            getattr(entry, \"title\", \"\")\n",
        "        )\n",
        "\n",
        "        url = normalize_url(\n",
        "            getattr(entry, \"link\", \"\")\n",
        "        )\n",
        "\n",
        "        description = clean_text(\n",
        "            getattr(\n",
        "                entry,\n",
        "                \"summary\",\n",
        "                getattr(entry, \"description\", \"\"),\n",
        "            )\n",
        "        )\n",
        "\n",
        "        published_at = clean_text(\n",
        "            getattr(\n",
        "                entry,\n",
        "                \"published\",\n",
        "                getattr(entry, \"updated\", \"\"),\n",
        "            )\n",
        "        )\n",
        "\n",
        "        if not is_valid_article(title, url):\n",
        "            continue\n",
        "\n",
        "        articles.append(\n",
        "            NewsArticle(\n",
        "                title=title,\n",
        "                url=url,\n",
        "                source=get_source_from_url(url),\n",
        "                category=category,\n",
        "                published_at=published_at,\n",
        "                description=description[:2000],\n",
        "            )\n",
        "        )\n",
        "\n",
        "    logger.info(\n",
        "        \"Collected %d articles from %s\",\n",
        "        len(articles),\n",
        "        feed_url,\n",
        "    )\n",
        "\n",
        "    return articles\n",
