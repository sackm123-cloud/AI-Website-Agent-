        "\n",
        "        \"class\":\n",
        "            \"class_update\",\n",
        "    }\n",
        "\n",
        "    agent_name = aliases.get(\n",
        "        job_name.lower(),\n",
        "        job_name.lower(),\n",
        "    )\n",
        "\n",
        "    function = agents.get(\n",
        "        agent_name\n",
        "    )\n",
        "\n",
        "    if function is None:\n",
        "\n",
        "        logger.error(\n",
        "            \"Unknown or unavailable job: %s\",\n",
        "            job_name,\n",
        "        )\n",
        "\n",
        "        print(\n",
        "            \"Available jobs:\"\n",
        "        )\n",
        "\n",
        "        print(\n",
        "            \"  news\"\n",
        "        )\n",
        "\n",
        "        print(\n",
        "            \"  tip\"\n",
        "        )\n",
        "\n",
        "        print(\n",
        "            \"  project\"\n",
        "        )\n",
