        "        ]\n",
        "\n",
        "        try:\n",
        "\n",
        "            result = json.loads(\n",
        "                candidate\n",
        "            )\n",
        "\n",
        "            if isinstance(\n",
        "                result,\n",
        "                dict,\n",
        "            ):\n",
        "\n",
        "                return result\n",
        "\n",
