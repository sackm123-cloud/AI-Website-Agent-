        "    text = re.sub(\n",
        "        r\"^```json\\s*\",\n",
        "        \"\",\n",
        "        text,\n",
        "        flags=re.IGNORECASE,\n",
        "    )\n",
        "\n",
        "    text = re.sub(\n",
        "        r\"^```\\s*\",\n",
        "        \"\",\n",
