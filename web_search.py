        "# =========================================================\n",
        "# RSS PARSER\n",
        "# =========================================================\n",
        "\n",
        "def parse_rss(\n",
        "    xml: str,\n",
        "    source_name: str,\n",
        "    category: str,\n",
        ") -> list[dict[str, Any]]:\n",
        "    \"\"\"\n",
        "    Parse RSS/Atom feed.\n",
        "\n",
        "    Uses BeautifulSoup rather than depending\n",
        "    on feedparser.\n",
        "    \"\"\"\n",
        "\n",
        "    if not xml:\n",
        "\n",
        "        return []\n",
        "\n",
        "    soup = BeautifulSoup(\n",
        "        xml,\n",
        "        \"xml\",\n",
        "    )\n",
        "\n",
        "    items = soup.find_all(\n",
        "        [\"item\", \"entry\"]\n",
        "    )\n",
        "\n",
        "    articles = []\n",
        "\n",
        "    for item in items:\n",
        "\n",
        "        title_tag = item.find(\n",
        "            \"title\"\n",
        "        )\n",
        "\n",
        "        link_tag = item.find(\n",
        "            \"link\"\n",
        "        )\n",
        "\n",
        "        description_tag = (\n",
        "            item.find(\n",
        "                \"description\"\n",
        "            )\n",
        "            or item.find(\n",
        "                \"summary\"\n",
        "            )\n",
        "            or item.find(\n",
        "                \"content\"\n",
        "            )\n",
        "        )\n",
        "\n",
        "        date_tag = (\n",
        "            item.find(\n",
        "                \"pubDate\"\n",
        "            )\n",
        "            or item.find(\n",
        "                \"published\"\n",
        "            )\n",
        "            or item.find(\n",
        "                \"updated\"\n",
        "            )\n",
        "        )\n",
        "\n",
        "        author_tag = (\n",
        "            item.find(\n",
        "                \"author\"\n",
        "            )\n",
        "            or item.find(\n",
        "                \"dc:creator\"\n",
        "            )\n",
        "        )\n",
        "\n",
        "        title = (\n",
        "            title_tag.get_text(\n",
        "                \" \",\n",
        "                strip=True,\n",
        "            )\n",
        "            if title_tag\n",
        "            else \"\"\n",
        "        )\n",
        "\n",
        "        # RSS <link>\n",
        "        url = \"\"\n",
        "\n",
        "        if link_tag:\n",
        "\n",
        "            url = (\n",
        "                link_tag.get(\n",
        "                    \"href\",\n",
        "                    \"\"\n",
        "                )\n",
        "                or link_tag.get_text(\n",
        "                    strip=True\n",
        "                )\n",
        "            )\n",
        "\n",
        "        # Atom sometimes stores URL in href.\n",
        "        if (\n",
        "            not url\n",
        "            and link_tag\n",
        "        ):\n",
        "\n",
        "            url = link_tag.get(\n",
        "                \"href\",\n",
        "                \"\",\n",
        "            )\n",
        "\n",
        "        description = (\n",
        "            description_tag.get_text(\n",
        "                \" \",\n",
        "                strip=True,\n",
        "            )\n",
        "            if description_tag\n",
        "            else \"\"\n",
        "        )\n",
        "\n",
        "        author = (\n",
        "            author_tag.get_text(\n",
        "                \" \",\n",
        "                strip=True,\n",
        "            )\n",
        "            if author_tag\n",
        "            else \"\"\n",
        "        )\n",
        "\n",
        "        published = (\n",
        "            date_tag.get_text(\n",
        "                \" \",\n",
        "                strip=True,\n",
        "            )\n",
        "            if date_tag\n",
        "            else \"\"\n",
        "        )\n",
        "\n",
        "        published_at = parse_date(\n",
        "            published\n",
        "        )\n",
        "\n",
        "        if not title or not url:\n",
        "\n",
        "            continue\n",
        "\n",
        "        articles.append(\n",
        "            {\n",
        "                \"title\": clean_text(\n",
        "                    title\n",
        "                ),\n",
        "\n",
        "                \"url\": url.strip(),\n",
        "\n",
        "                \"description\": clean_text(\n",
        "                    description\n",
        "                ),\n",
        "\n",
        "                \"source\": source_name,\n",
        "\n",
        "                \"category\": category,\n",
        "\n",
        "                \"author\": clean_text(\n",
        "                    author\n",
        "                ),\n",
        "\n",
        "                \"published\": (\n",
        "                    published_at.isoformat()\n",
        "                    if published_at\n",
        "                    else \"\"\n",
        "                ),\n",
        "            }\n",
        "        )\n",
        "\n",
        "    return articles\n",
        "\n",
