        "# =========================================================\n",
        "# KEYWORD FILTER\n",
        "# =========================================================\n",
        "\n",
        "def filter_keywords(\n",
        "    articles: list[dict[str, Any]],\n",
        "    keywords: Optional[\n",
        "        list[str]\n",
        "    ] = None,\n",
        ") -> list[dict[str, Any]]:\n",
        "    \"\"\"\n",
        "    Keep articles matching keywords.\n",
        "    \"\"\"\n",
        "\n",
        "    if not keywords:\n",
        "\n",
        "        return articles\n",
        "\n",
        "    keywords_lower = [\n",
        "        keyword.lower()\n",
        "        for keyword in keywords\n",
        "    ]\n",
        "\n",
        "    results = []\n",
        "\n",
        "    for article in articles:\n",
        "\n",
        "        searchable = \" \".join(\n",
        "            [\n",
        "                article.get(\n",
        "                    \"title\",\n",
        "                    \"\",\n",
        "                ),\n",
        "                article.get(\n",
        "                    \"description\",\n",
        "                    \"\",\n",
        "                ),\n",
        "                article.get(\n",
        "                    \"category\",\n",
        "                    \"\",\n",
        "                ),\n",
        "            ]\n",
        "        ).lower()\n",
        "\n",
        "        if any(\n",
        "            keyword in searchable\n",
        "            for keyword in keywords_lower\n",
        "        ):\n",
        "\n",
        "            results.append(\n",
        "                article\n",
        "            )\n",
        "\n",
        "    return results\n",
        "\n",
