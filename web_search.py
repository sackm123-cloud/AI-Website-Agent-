        "# =========================================================\n",
        "# DUPLICATE REMOVAL\n",
        "# =========================================================\n",
        "\n",
        "def article_key(\n",
        "    article: dict[str, Any],\n",
        ") -> str:\n",
        "    \"\"\"\n",
        "    Generate stable article identifier.\n",
        "    \"\"\"\n",
        "\n",
        "    url = article.get(\n",
        "        \"url\",\n",
        "        \"\",\n",
        "    ).strip().lower()\n",
        "\n",
        "    if url:\n",
        "\n",
        "        return hashlib.sha256(\n",
        "            url.encode(\n",
        "                \"utf-8\"\n",
        "            )\n",
        "        ).hexdigest()\n",
        "\n",
        "    title = article.get(\n",
        "        \"title\",\n",
        "        \"\",\n",
        "    ).strip().lower()\n",
        "\n",
        "    return hashlib.sha256(\n",
        "        title.encode(\n",
        "            \"utf-8\"\n",
        "        )\n",
        "    ).hexdigest()\n",
        "\n",
        "\n",
        "def remove_duplicates(\n",
        "    articles: list[dict[str, Any]],\n",
        ") -> list[dict[str, Any]]:\n",
        "    \"\"\"\n",
        "    Remove duplicate articles.\n",
        "    \"\"\"\n",
        "\n",
        "    seen = set()\n",
        "\n",
        "    results = []\n",
        "\n",
        "    for article in articles:\n",
        "\n",
        "        key = article_key(\n",
        "            article\n",
        "        )\n",
        "\n",
        "        if key in seen:\n",
        "\n",
        "            continue\n",
        "\n",
        "        seen.add(key)\n",
        "\n",
        "        results.append(\n",
        "            article\n",
        "        )\n",
        "\n",
        "    return results\n",
        "\n",
        "\n",
        "# =========================================================\n",
        "# SORT ARTICLES\n",
        "# =========================================================\n",
        "\n",
        "def sort_articles(\n",
        "    articles: list[dict[str, Any]],\n",
        ") -> list[dict[str, Any]]:\n",
        "    \"\"\"\n",
        "    Sort newest articles first.\n",
        "    \"\"\"\n",
        "\n",
        "    def sort_key(\n",
        "        article: dict[str, Any],\n",
        "    ):\n",
        "\n",
        "        value = article.get(\n",
        "            \"published\",\n",
        "            \"\",\n",
        "        )\n",
        "\n",
        "        if not value:\n",
        "\n",
        "            return datetime.min.replace(\n",
        "                tzinfo=timezone.utc\n",
        "            )\n",
        "\n",
        "        try:\n",
        "\n",
        "            return datetime.fromisoformat(\n",
        "                value\n",
        "            )\n",
        "\n",
        "        except ValueError:\n",
        "\n",
        "            return datetime.min.replace(\n",
        "                tzinfo=timezone.utc\n",
        "            )\n",
        "\n",
        "    return sorted(\n",
        "        articles,\n",
        "        key=sort_key,\n",
        "        reverse=True,\n",
        "    )\n",
        "\n",
