        "def load_rss_library():\n",
        "    \"\"\"\n",
        "    Import feedparser only when needed.\n",
        "\n",
        "    Install with:\n",
        "        pip install feedparser\n",
        "    \"\"\"\n",
        "\n",
        "    try:\n",
        "        import feedparser\n",
        "\n",
        "        return feedparser\n",
        "\n",
        "    except ImportError as exc:\n",
        "        raise ImportError(\n",
        "            \"feedparser is required for news collection. \"\n",
        "            \"Install it with: pip install feedparser\"\n",
        "        ) from exc\n",
