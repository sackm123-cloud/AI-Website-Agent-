        "# =========================================================\n",
        "# MULTI-CATEGORY SEARCH\n",
        "# =========================================================\n",
        "\n",
        "def search_news(\n",
        "    categories: Optional[\n",
        "        list[str]\n",
        "    ] = None,\n",
        "    hours: int = 48,\n",
        "    limit: int = MAX_ARTICLES,\n",
        "    keywords: Optional[\n",
        "        list[str]\n",
        "    ] = None,\n",
        ") -> list[dict[str, Any]]:\n",
        "    \"\"\"\n",
        "    Collect current AI/Robotics/STEM news.\n",
        "\n",
        "    Example:\n",
        "\n",
        "        articles = search_news(\n",
        "            categories=[\n",
        "                \"AI\",\n",
        "                \"Robotics\",\n",
        "                \"Electronics\",\n",
        "            ],\n",
        "            hours=24,\n",
        "            limit=15,\n",
        "        )\n",
        "    \"\"\"\n",
        "\n",
        "    if categories is None:\n",
        "\n",
        "        categories = [\n",
        "            \"AI\",\n",
        "            \"Robotics\",\n",
        "            \"Electronics\",\n",
        "            \"IoT\",\n",
        "        ]\n",
        "\n",
        "    all_articles = []\n",
        "\n",
        "    for category in categories:\n",
        "\n",
        "        articles = search_rss(\n",
        "            category\n",
